package com.lovesite.backup;

import com.lovesite.media.processing.ProcessRunner;
import com.lovesite.storage.StorageService;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.scheduling.annotation.Scheduled;
import org.springframework.stereotype.Service;

import java.io.IOException;
import java.io.InputStream;
import java.net.URI;
import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Timestamp;
import java.time.Instant;
import java.time.LocalDate;
import java.time.ZoneId;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.UUID;
import java.util.concurrent.atomic.AtomicBoolean;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Nightly backup to a second bucket.
 *
 * Media: only what cannot be rebuilt, the originals and the album songs (thumbnails, display images and loops are
 * regenerated by the processing queue). Incremental: an object that is already at the target with the same key and size
 * is skipped. Copies are streamed from the main bucket to the target. Keys are never rewritten, so a restore is a plain
 * copy back. A purged original stays at the target for the retention period (30 days), then the run deletes it there.
 *
 * Database: pg_dump in custom format to db/YYYY-MM-DD.dump, the last 14 days are kept.
 */
@Service
public class BackupService {

    private static final Logger log = LoggerFactory.getLogger(BackupService.class);
    private static final ZoneId ZONE = ZoneId.of("Europe/Istanbul");
    static final String MEDIA = "MEDIA";
    static final String DB = "DB";
    static final String DB_PREFIX = "db/";
    private static final Pattern DUMP_NAME = Pattern.compile("^db/(\\d{4}-\\d{2}-\\d{2})\\.dump$");

    public record Run(String kind, String status, Instant startedAt, Instant finishedAt,
                      Long objectCount, Long totalBytes, Long copiedCount, String message) {
    }

    public record Status(boolean enabled, Run media, Run db) {
    }

    private record Source(String key, long size, String contentType) {
    }

    private final JdbcTemplate jdbc;
    private final StorageService storage;
    private final BackupTarget target;
    private final BackupProperties properties;
    private final String dbUrl;
    private final String dbUser;
    private final String dbPassword;
    private final AtomicBoolean running = new AtomicBoolean();
    private final com.lovesite.role.Roles roles;

    public BackupService(JdbcTemplate jdbc, StorageService storage, BackupTarget target, BackupProperties properties,
                         @Value("${spring.datasource.url}") String dbUrl,
                         @Value("${spring.datasource.username}") String dbUser,
                         @Value("${spring.datasource.password:}") String dbPassword,
                         com.lovesite.role.Roles roles) {
        this.roles = roles;
        this.jdbc = jdbc;
        this.storage = storage;
        this.target = target;
        this.properties = properties;
        this.dbUrl = dbUrl;
        this.dbUser = dbUser;
        this.dbPassword = dbPassword;
    }

    public boolean enabled() {
        return target.enabled();
    }

    // ---- scheduling

    /** 04:00, after the 03:30 trash purge has written its records. A failure of one half never skips the other. */
    @Scheduled(cron = "0 0 4 * * *", zone = "Europe/Istanbul")
    public void scheduled() {
        if (roles.runs(com.lovesite.role.Roles.Job.BACKUP) && enabled()) runAll();
    }

    /**
     * "Back up now" from the admin screen. The web service runs no jobs, so the request is a row the worker picks up
     * (OpsRequestPoller); in the all-in-one process the same poller runs it a few seconds later.
     */
    public void requestRun() {
        jdbc.update("INSERT INTO ops_request (kind) SELECT 'BACKUP' WHERE NOT EXISTS (SELECT 1 FROM ops_request WHERE kind = 'BACKUP')");
    }

    /** Requested, running in this process, or running in another one (the worker) according to the run records. */
    public boolean isBusy() {
        if (running.get()) return true;
        Integer n = jdbc.queryForObject("SELECT (SELECT count(*) FROM ops_request WHERE kind = 'BACKUP') "
                + "+ (SELECT count(*) FROM backup_run WHERE status = 'RUNNING' AND started_at > now() - interval '12 hours')", Integer.class);
        return n != null && n > 0;
    }

    /** Worker side: takes the pending requests (one run covers all of them). */
    public boolean takeRequests() {
        Integer taken = jdbc.queryForObject("WITH t AS (DELETE FROM ops_request WHERE id IN "
                + "(SELECT id FROM ops_request WHERE kind = 'BACKUP' FOR UPDATE SKIP LOCKED) RETURNING 1) SELECT count(*) FROM t", Integer.class);
        return taken != null && taken > 0;
    }

    /** Both halves, one after the other. Returns false when a run is already in progress or backup is off. */
    public boolean runAll() {
        if (!enabled()) return false;
        if (!running.compareAndSet(false, true)) return false;
        try {
            runDb(LocalDate.now(ZONE));
            runMedia(Instant.now());
            return true;
        } finally {
            running.set(false);
        }
    }

    public boolean isRunning() {
        return running.get();
    }

    /** A run record still marked RUNNING at startup belongs to a process that died. */
    public void markInterruptedRuns() {
        int n = jdbc.update("UPDATE backup_run SET status = 'FAILED', finished_at = now(), message = 'interrupted by a restart' WHERE status = 'RUNNING'");
        if (n > 0) log.warn("Marked {} unfinished backup run(s) as failed", n);
    }

    // ---- status

    public Status status() {
        return new Status(enabled(), last(MEDIA), last(DB));
    }

    private Run last(String kind) {
        List<Run> rows = jdbc.query("SELECT kind, status, started_at, finished_at, object_count, total_bytes, copied_count, message "
                        + "FROM backup_run WHERE kind = ? ORDER BY started_at DESC LIMIT 1",
                (rs, i) -> new Run(rs.getString(1), rs.getString(2), rs.getTimestamp(3).toInstant(),
                        rs.getTimestamp(4) == null ? null : rs.getTimestamp(4).toInstant(),
                        (Long) rs.getObject(5), (Long) rs.getObject(6), (Long) rs.getObject(7), rs.getString(8)), kind);
        return rows.isEmpty() ? null : rows.get(0);
    }

    private UUID begin(String kind) {
        return jdbc.queryForObject("INSERT INTO backup_run (kind, status) VALUES (?, 'RUNNING') RETURNING id", UUID.class, kind);
    }

    private void finish(UUID id, boolean ok, long count, long bytes, long copied, String message) {
        jdbc.update("UPDATE backup_run SET status = ?, finished_at = now(), object_count = ?, total_bytes = ?, copied_count = ?, message = ? WHERE id = ?",
                ok ? "OK" : "FAILED", count, bytes, copied, message == null ? null : message.substring(0, Math.min(400, message.length())), id);
    }

    // ---- media

    public Run runMedia(Instant now) {
        UUID id = begin(MEDIA);
        long copied = 0;
        int failed = 0;
        try {
            Map<String, Long> present = target.list("spaces/");
            List<Source> sources = jdbc.query(
                    "SELECT original_key, size_bytes, content_type FROM media WHERE status IN ('UPLOADED','PROCESSING','READY','FAILED') "
                            + "UNION ALL SELECT music_key, music_size_bytes, music_content_type FROM album WHERE music_key IS NOT NULL",
                    (rs, i) -> new Source(rs.getString(1), rs.getLong(2), rs.getString(3)));
            for (Source s : sources) {
                Long have = present.get(s.key());
                if (have != null && have == s.size()) continue;
                try (InputStream in = storage.openStream(s.key())) {
                    target.put(s.key(), in, s.size(), s.contentType());
                    present.put(s.key(), s.size());
                    copied++;
                } catch (Exception e) {
                    failed++;
                    log.warn("Backup of {} failed: {}", s.key(), e.toString());
                }
            }

            // purged originals stay for the retention period, then go
            Timestamp cutoff = Timestamp.from(now.minus(properties.purgedRetention()));
            List<String> expired = jdbc.queryForList("SELECT object_key FROM purged_object WHERE purged_at < ?", String.class, cutoff);
            for (String key : expired) {
                try {
                    target.delete(key);
                    present.remove(key);
                    jdbc.update("DELETE FROM purged_object WHERE object_key = ?", key);
                } catch (Exception e) {
                    failed++;
                    log.warn("Could not delete expired backup {}: {}", key, e.toString());
                }
            }

            long bytes = present.values().stream().mapToLong(Long::longValue).sum();
            String message = failed == 0 ? null : failed + " object(s) could not be copied or removed, see the log";
            finish(id, failed == 0, present.size(), bytes, copied, message);
            log.info("Media backup finished: {} copied, {} at target, {} failed", copied, present.size(), failed);
        } catch (Exception e) {
            log.error("Media backup failed: {}", e.toString());
            finish(id, false, 0, 0, copied, e.toString());
        }
        return last(MEDIA);
    }

    // ---- database

    public Run runDb(LocalDate today) {
        UUID id = begin(DB);
        Path dump = null;
        try {
            dump = Files.createTempFile("dump-", ".dump");
            Files.delete(dump); // pg_dump creates it itself
            runPgDump(dump);
            String key = DB_PREFIX + today + ".dump";
            target.putFile(key, dump, "application/octet-stream");

            // rotation: keep the newest `dbKeepDays` calendar days, today included
            LocalDate oldestKept = today.minusDays(properties.dbKeepDays() - 1L);
            Map<String, Long> present = target.list(DB_PREFIX);
            for (String existing : new ArrayList<>(present.keySet())) {
                Matcher m = DUMP_NAME.matcher(existing);
                if (m.matches() && LocalDate.parse(m.group(1)).isBefore(oldestKept)) {
                    target.delete(existing);
                    present.remove(existing);
                }
            }
            long bytes = present.values().stream().mapToLong(Long::longValue).sum();
            finish(id, true, present.size(), bytes, 1, null);
            log.info("Database backup finished: {} ({} bytes), {} dump(s) at target", key, Files.size(dump), present.size());
        } catch (Exception e) {
            if (e instanceof InterruptedException) Thread.currentThread().interrupt();
            log.error("Database backup failed: {}", e.toString());
            finish(id, false, 0, 0, 0, e.toString());
        } finally {
            if (dump != null) {
                try {
                    Files.deleteIfExists(dump);
                } catch (IOException ignored) {
                    // temp dir is cleaned on restart
                }
            }
        }
        return last(DB);
    }

    private void runPgDump(Path out) throws IOException, InterruptedException {
        URI uri = URI.create(dbUrl.substring("jdbc:".length()));
        List<String> command = new ArrayList<>(List.of("pg_dump", "--format=custom", "--no-password",
                "--host", uri.getHost(), "--port", String.valueOf(uri.getPort() > 0 ? uri.getPort() : 5432),
                "--username", dbUser, "--dbname", uri.getPath().substring(1), "--file", out.toString()));
        Map<String, String> env = new HashMap<>();
        // the password goes through the environment, never the command line (visible in the process list and in errors)
        if (!dbPassword.isEmpty()) env.put("PGPASSWORD", dbPassword);
        String query = uri.getQuery();
        if (query != null) {
            for (String part : query.split("&")) {
                if (part.startsWith("sslmode=")) env.put("PGSSLMODE", part.substring("sslmode=".length()));
            }
        }
        ProcessRunner.Result version = ProcessRunner.run(List.of("pg_dump", "--version"), java.time.Duration.ofSeconds(10));
        log.info("Running {}", version.stdout().trim());
        ProcessRunner.Result result = ProcessRunner.run(command, env, properties.dumpTimeout());
        if (result.exitCode() != 0) {
            throw new IOException("pg_dump exited with " + result.exitCode() + ": " + result.stderr().trim());
        }
    }
}
